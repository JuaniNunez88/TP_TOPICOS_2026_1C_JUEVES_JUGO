void fuente_dibujar_char(const t_fuente *f, char c, int x, int y, int color)
{
    if (c < FUENTE_CHAR_MIN || c > FUENTE_CHAR_MAX)
        return;

    int idx = c - FUENTE_CHAR_MIN;
    for (int fila = 0; fila < f->alto; fila++)
    {
        unsigned char byte = f->letra[idx][fila];
        for (int bit = 7; bit >= 0; bit--)
            if (byte & (1 << bit))
                gbt_dibujar_pixel(x + (7 - bit), y + fila, color);
    }
}

void fuente_dibujar_texto(const t_fuente *f, const char *texto, int x, int y, int color)
{
    int cursor_x = x;
    for (int i = 0; texto[i] != '\0'; i++)
    {
        fuente_dibujar_char(f, texto[i], cursor_x, y, color);
        cursor_x += f->ancho + 1;
    }
}
